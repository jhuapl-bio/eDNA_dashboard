#!/usr/bin/env bash
# Write frontend/config.js (the API base URL the dashboard calls).
#   API_URL=https://mbon.example.org/api bash frontend/make-config.sh
# Order of precedence: $API_URL env var, API_URL= in api/.env, then the repo-root
# .env, then http://127.0.0.1:5050/api.
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(dirname "$SCRIPT_DIR")"

read_env() {  # read_env FILE -> value of API_URL= (quotes stripped)
  [ -f "$1" ] && grep -E '^API_URL=' "$1" | tail -n1 | cut -d'=' -f2- | tr -d '"'"'" || true
}

URL="${API_URL:-}"
[ -n "$URL" ] || URL="$(read_env "$REPO_DIR/api/.env")"
[ -n "$URL" ] || URL="$(read_env "$REPO_DIR/.env")"
URL="${URL:-http://127.0.0.1:5050/api}"

case "$URL" in
  http://*|https://*|/*) ;;
  *) echo "✖ API_URL must start with http://, https:// or / (got: $URL)" >&2; exit 1 ;;
esac

cat > "$SCRIPT_DIR/config.js" <<JS
// Auto-generated by make-config.sh — do not edit by hand.
window.MBON_API_URL = "$URL";
JS
echo "✔  frontend/config.js written with API_URL=$URL"
